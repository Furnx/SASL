        self.UserAgent = header.get("HTTP_USER_AGENT")
        self.Accept = header.get("HTTP_ACCEPT")
        self.AcceptLang = header.get("HTTP_ACCEPT_LANGUAGE")
        self.AcceptEncoding = header.get("HTTP_ACCEPT_ENCODING")
        self.Connection = header.get("HTTP_CONNECTION")
        self.Cookie = header.get("HTTP_COOKIE")
        self.UpgradeInsecureRequests = header.get("HTTP_UPGRADE_INSECURE_REQUESTS")
        self.SEC_FETCH_DEST = header.get("HTTP_SEC_FETCH_DEST")
        self.SEC_FETCH_MODE = header.get("HTTP_SEC_FETCH_MODE")
        self.SEC_FETCH_SITE = header.get("HTTP_SEC_FETCH_SITE")
        self.SEC_FETCH_USER = header.get("HTTP_SEC_FETCH_USER")

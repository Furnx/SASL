        self.run_once = header.get("wsgi.run_once")
        self.WSGISocket = header.get("werkzeug.socket")
        self.ServerSocket = header.get("SERVER_SOFTWARE")
        self.RequestMethod = header.get("REQUEST_METHOD")
        self.ScriptName = header.get("SCRIPT_NAME")
        self.PathInfo = header.get("PATH_INFO")
        self.QueryString = header.get("QUERY_STRING")
        self.ReqURL = header.get("REQUEST_URI")
        self.RawUrl = header.get("RAW_URI")
